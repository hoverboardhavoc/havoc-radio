#!/usr/bin/env python3
"""Generate the Pip and Facet font tables and the UI icons as C++ from ui/prototype.html.

usage: gen_fonts.py <prototype.html> <out.cpp>

The prototype's PIP, FACET and ICONS tables are the source of truth; the firmware tables are generated
from them on every build so the two cannot drift apart.
"""
import json
import re
import sys

# Icons the firmware draws. The prototype has more; only these are emitted.
USED_ICONS = ["presets", "settings", "volume", "muted"]


def block(src, start):
    """Return the text of the {...} object literal that follows `start`."""
    i = src.index(start)
    i = src.index("{", i)
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    raise ValueError("unterminated block " + start)


KEY = r"""(?:'((?:\\.|[^'\\])+)'|"((?:\\.|[^"\\])+)"|([A-Za-z0-9_]+))"""


def key_of(m, base=1):
    for g in range(base, base + 3):
        if m.group(g) is not None:
            k = m.group(g)
            if g < base + 2:
                k = k.encode().decode("unicode_escape") if "\\" in k else k
            return k
    raise ValueError


def parse_pip(src):
    body = block(src, "const PIP =")
    glyphs = {}
    for m in re.finditer(KEY + r"\s*:\s*G\('([^']*)'\)", body):
        k = key_of(m)
        rows = m.group(4).split(" ")
        w = len(rows[0])
        if any(len(r) != w for r in rows) or len(rows) not in (6, 7) or w > 8:
            raise ValueError(f"bad glyph {k!r}")
        glyphs[k] = rows
    return glyphs


def parse_facet(src):
    body = block(src, "const FACET =")
    glyphs = {}
    for m in re.finditer(KEY + r"\s*:\s*(\[\[\[.*?\]\]\])\s*,", body):
        glyphs[key_of(m)] = json.loads(m.group(4))
    return glyphs


def parse_icons(src):
    body = block(src, "const ICONS =")
    icons = {}
    for m in re.finditer(r"([A-Za-z]+)\s*:\s*\[([^\]]*)\]", body):
        icons[m.group(1)] = re.findall(r"'([.#]+)'", m.group(2))
    return icons


def rowbits(row):
    return sum(1 << i for i, c in enumerate(row) if c == "#")


def emit(pip, facet, icons):
    out = ["// Generated by tools/gen_fonts.py from ui/prototype.html. Do not edit.",
           '#include "gfx_fonts.h"', "", "namespace gfx {", ""]
    out.append("const PipGlyph kPip[] = {")
    for k in sorted(pip, key=ord):
        rows = pip[k]
        bits = ", ".join(f"0x{rowbits(r):02x}" for r in rows)
        out.append(f"    {{0x{ord(k):04x}, {len(rows[0])}, {len(rows)}, {{{bits}}}}},")
    out.append("};")
    out.append(f"const int kPipCount = {len(pip)};")
    out.append("")
    # Facet: per glyph, polyline count; per polyline, point count then x,y pairs.
    data, index = [], []
    for k in sorted(facet):
        index.append((k, len(data)))
        data.append(len(facet[k]))
        for pl in facet[k]:
            data.append(len(pl))
            for x, y in pl:
                data += [x, y]
    out.append("const uint8_t kFacetData[] = {")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(str(v) for v in data[i:i + 16]) + ",")
    out.append("};")
    out.append("const FacetGlyph kFacet[] = {")
    for k, off in index:
        out.append(f"    {{'{k}', {off}}},")
    out.append("};")
    out.append(f"const int kFacetCount = {len(index)};")
    out.append("")
    out.append("const IconBits kIcons[] = {")
    for name in USED_ICONS:
        rows = icons[name]
        bits = ", ".join(f"0x{rowbits(r):02x}" for r in rows)
        out.append(f"    {{{len(rows[0])}, {len(rows)}, {{{bits}}}}},  // {name}")
    out.append("};")
    out.append("")
    out.append("}  // namespace gfx")
    return "\n".join(out) + "\n"


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    text = emit(parse_pip(src), parse_facet(src), parse_icons(src))
    try:
        if open(sys.argv[2], encoding="utf-8").read() == text:
            return
    except OSError:
        pass
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
