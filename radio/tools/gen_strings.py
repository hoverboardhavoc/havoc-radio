#!/usr/bin/env python3
"""Generate the UI string tables as C++ from ui/prototype.html.

usage: gen_strings.py <prototype.html> <out dir>

Reads the prototype's LANGS and STRINGS tables and writes i18n_strings.h (key enum, language list) and
i18n_strings.cpp (per language one blob of its NUL-terminated UTF-8 strings in key order, and each string's
offset in it). Also writes i18n_strings.jsonl, each language as the JSON object GET /api/strings sends, one per
line, for the host test; it is not part of the firmware. Fails when a language lacks a key, its placeholders
differ from English, or its blob passes 65,535 bytes.
"""
import json
import os
import re
import sys


def parse(src):
    langs = json.loads(re.search(r"const LANGS = (\[.*?\]);\n", src, re.S).group(1))
    strings = json.loads(re.search(r"const STRINGS = (\{.*?\n\});\n", src, re.S).group(1))
    return langs, strings


def check(langs, strings):
    en = strings["en"]
    ph = {k: re.findall(r"%[ds%]", v) for k, v in en.items()}
    for code, _ in langs:
        t = strings[code]
        if set(t) != set(en):
            sys.exit(f"{code}: keys differ from English: {sorted(set(t) ^ set(en))}")
        for k, v in t.items():
            if re.findall(r"%[ds%]", v) != ph[k]:
                sys.exit(f"{code}.{k}: placeholders differ from English")


def c_str(s):
    out = []
    for b in s.encode("utf-8"):
        if b == 0x22 or b == 0x5C:
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


BLOB_MAX = 0xFFFF  # the offsets are 16-bit


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    outdir = sys.argv[2]
    langs, strings = parse(src)
    check(langs, strings)
    keys = list(strings["en"])
    h = ["// Generated by tools/gen_strings.py from ui/prototype.html. Do not edit.", "#pragma once",
         "#include <cstdint>", "", "namespace i18n {", "",
         "enum class Str : uint16_t {"]
    h += [f"    {k}," for k in keys]
    h += ["};", f"constexpr int kStrCount = {len(keys)};", f"constexpr int kLangCount = {len(langs)};", "",
          "extern const char* const kKey[kStrCount];",
          "extern const char* const kLangCode[kLangCount];",
          "extern const char* const kLangName[kLangCount];  // each language by its own name",
          "extern const char* const kBlob[kLangCount];  // the language's strings, NUL-terminated, in key order",
          "extern const uint16_t kOffset[kLangCount][kStrCount];  // each string's offset in its blob", "",
          "inline const char* tr(int lang, Str s) {",
          "    const int l = lang >= 0 && lang < kLangCount ? lang : 0;",
          "    return kBlob[l] + kOffset[l][static_cast<int>(s)];",
          "}", "", "}  // namespace i18n", ""]
    c = ["// Generated by tools/gen_strings.py from ui/prototype.html. Do not edit.",
         '#include "i18n_strings.h"', "", "namespace i18n {", "",
         "const char* const kKey[kStrCount] = {" + ", ".join(c_str(k) for k in keys) + "};",
         "const char* const kLangCode[kLangCount] = {" + ", ".join(c_str(l[0]) for l in langs) + "};",
         "const char* const kLangName[kLangCount] = {" + ", ".join(c_str(l[1]) for l in langs) + "};",
         ""]
    offsets = []
    for i, (code, _) in enumerate(langs):
        offs, size = [], 0
        c.append(f"const char kBlob{i}[] =  // {code}")
        for k in keys:
            offs.append(size)
            size += len(strings[code][k].encode("utf-8")) + 1
            c.append("    " + c_str(strings[code][k] + "\0"))
        c[-1] += ";"
        if size > BLOB_MAX:
            sys.exit(f"{code}: the strings are {size} bytes, more than {BLOB_MAX}")
        offsets.append(offs)
    c.append("const char* const kBlob[kLangCount] = {" + ", ".join(f"kBlob{i}" for i in range(len(langs))) + "};")
    c.append("const uint16_t kOffset[kLangCount][kStrCount] = {")
    c += ["    {" + ", ".join(map(str, offs)) + "}," for offs in offsets]
    c.append("};")
    jsonl = [json.dumps(strings[code], ensure_ascii=False, separators=(",", ":")) for code, _ in langs] + [""]
    c += ["", "}  // namespace i18n", ""]
    for name, text in (("i18n_strings.h", h), ("i18n_strings.cpp", c), ("i18n_strings.jsonl", jsonl)):
        path = os.path.join(outdir, name)
        body = "\n".join(text)
        try:
            if open(path, encoding="utf-8").read() == body:
                continue
        except OSError:
            pass
        with open(path, "w", encoding="utf-8") as f:
            f.write(body)


if __name__ == "__main__":
    main()
